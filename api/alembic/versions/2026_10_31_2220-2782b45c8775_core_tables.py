def lock_down_tables(tables: list[str]) -> None:
    """Enable RLS (no policies) and revoke browser-role access. Call this for every new table."""
    for table in tables:
        op.execute(f'ALTER TABLE "{table}" ENABLE ROW LEVEL SECURITY')
    for role in BROWSER_ROLES:
        names = ", ".join(f'"{table}"' for table in tables)
